"""Evaluate rules / transformer / hybrid detectors on the held-out test sets.

Usage (from backend/, venv active):
    python ../ml/scripts/evaluate.py --model ../ml/artifacts/pii-minilm-v1/best --name minilm-v1
    python ../ml/scripts/evaluate.py --model ../ml/artifacts/pii-minilm-v1/best --name smoke --limit 300

Outputs ml/evaluation/<name>/results.json (machine-readable) and report.md (human-readable).
No number in the report is hand-written: everything is computed from the prediction files here.
The test sets are read-only inputs; nothing in this script feeds back into training or model selection.
"""
import argparse
import json
import platform
import random
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pii_ml.dataio import read_jsonl  # noqa: E402
from pii_ml.metrics import evaluate  # noqa: E402

TEST_SETS = {
    "ylemis": "Ylemis India-PII Benchmark (10k, CC0; 14 language/format slices; evaluation-only)",
    "maskara_template_disjoint": "Maskara template-disjoint eval (15k; template families never seen in training)",
    "maskara_real_world": "Maskara real-world eval (2.6k; hand-curated Indian text)",
    "indiapii": "IndiaPII-Bench held-out documents (bucket 80-99 of the original 2,000)",
}


def to_spans(dets) -> list[dict]:
    return [{"start": d.start, "end": d.end, "type": d.entity_type} for d in dets]


def build_systems(model_dir: str | None, which: list[str]):
    from app.ml.hybrid import resolve
    from app.ml.rules import detect_rules

    min_conf = 0.3
    ner = None
    if model_dir and any(s in which for s in ("transformer", "hybrid")):
        from app.ml.transformer import TransformerDetector

        ner = TransformerDetector(model_dir, local_files_only=True, min_score=0.5)
    systems = {}
    if "rules" in which:
        systems["rules"] = lambda text: resolve(detect_rules(text), min_conf)
    if "transformer" in which and ner:
        systems["transformer"] = lambda text: resolve(ner.detect(text), min_conf)
    if "hybrid" in which and ner:
        systems["hybrid"] = lambda text: resolve(detect_rules(text) + ner.detect(text), min_conf)
    return systems, ner


def run_system(fn, docs: list[dict]) -> tuple[dict, dict]:
    preds, lat = {}, []
    for d in docs:
        t0 = time.perf_counter()
        preds[d["id"]] = to_spans(fn(d["text"]))
        lat.append((time.perf_counter() - t0) * 1000)
    lat.sort()
    perf = {
        "docs": len(docs), "mean_ms": round(statistics.fmean(lat), 2), "p50_ms": round(lat[len(lat) // 2], 2),
        "p95_ms": round(lat[int(len(lat) * 0.95)], 2), "docs_per_s": round(len(docs) / (sum(lat) / 1000), 1),
    }
    return preds, perf


def md_table(rows: list[list], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def render_report(res: dict) -> str:
    L = [f"# Evaluation report: {res['name']}", ""]
    L += [f"Generated by `ml/scripts/evaluate.py` on {res['generated_at']} ({res['platform']}, CPU only).", ""]
    meta = res.get("model_meta") or {}
    L += ["## Model under test", ""]
    if meta:
        L += [f"- Name: `{meta.get('name')}`; base encoder `{meta.get('base_model')}`; token-level BIO over {len(meta.get('labels', []))} labels",
              f"- Trained on {meta.get('train_docs')} documents; best validation strict micro-F1 {pct(meta.get('validation_micro_f1'))} at step {meta.get('best_step')} (validation split only)",
              "- Training data: synthetic only (Maskara + 70% of IndiaPII-Bench). See `docs/ml-pipeline.md`."]
    else:
        L += ["- No fine-tuned model supplied: only the rule detector was evaluated."]
    L += ["", f"Systems: {', '.join(res['systems'])}. Subsampling: "
          + ("none (full test sets)." if not res.get("limit") else f"first {res['limit']} documents per set (seeded shuffle) - NOT the full test sets."), ""]
    L += ["## Headline (strict span+type match, micro-averaged)", ""]
    rows = []
    for ts, per in res["results"].items():
        for sysname, r in per.items():
            m = r["metrics"]["strict"]["micro"]
            rows.append([ts, sysname, pct(m["precision"]), pct(m["recall"]), pct(m["f1"]),
                         pct(r["metrics"]["relaxed"]["micro"]["f1"]), pct(r["metrics"]["strict"]["macro_f1"]),
                         pct(r["metrics"]["clean_document_false_positive_rate"]["rate"]), r["perf"]["p50_ms"], r["perf"]["p95_ms"]])
    L += [md_table(rows, ["test set", "system", "P", "R", "F1 (strict)", "F1 (relaxed)", "macro F1", "clean-doc FPR", "p50 ms", "p95 ms"]), ""]
    L += ["*Strict* = exact start, end and type. *Relaxed* = same type and any overlap, one-to-one. *Clean-doc FPR* = share of "
          "documents with no gold PII where the system still predicted something. Latency is per document, single-threaded Python loop.", ""]
    for ts, desc in TEST_SETS.items():
        if ts not in res["results"]:
            continue
        L += [f"## {ts}", "", f"{desc}. Documents scored: {next(iter(res['results'][ts].values()))['metrics']['documents']}.", ""]
        systems = list(res["results"][ts])
        types = sorted({t for s in systems for t in res["results"][ts][s]["metrics"]["strict"]["per_type"]})
        rows = []
        for t in types:
            row = [t]
            for s in systems:
                pt = res["results"][ts][s]["metrics"]["strict"]["per_type"].get(t)
                row.append("-" if not pt else f"{pct(pt['f1'])} (P {pct(pt['precision'])} / R {pct(pt['recall'])}; n={pt['tp'] + pt['fn']})")
            rows.append(row)
        L += ["Per-type strict F1:", "", md_table(rows, ["type", *systems]), ""]
        best = "hybrid" if "hybrid" in systems else systems[-1]
        slices = res["results"][ts][best]["metrics"]["slices"]
        rows = [[k, v["docs"], pct(v["precision"]), pct(v["recall"]), pct(v["f1"])] for k, v in slices.items() if k.startswith("lang=")]
        if len(rows) > 1:
            L += [f"Per-language strict micro scores for `{best}` (languages with few training examples are expected to be weaker):", "",
                  md_table(rows, ["slice", "docs", "P", "R", "F1"]), ""]
        ex = res["results"][ts][best]["metrics"]["examples"]
        for kind, title in (("false_positives", "False positives"), ("false_negatives", "False negatives")):
            if ex[kind]:
                L += [f"{title} (first {min(len(ex[kind]), 8)}, `{best}`):", ""]
                L += [f"- `{e['type']}` `{e['text']!r}` in `...{e['context'].replace(chr(10), ' ')}...`" for e in ex[kind][:8]] + [""]
    L += ["## Limitations", "",
          "- All three datasets are synthetic; real-world performance will differ, usually downward.",
          "- Label mappings between datasets are explicit but lossy (see `ml/pii_ml/labelmap.py`); out-of-taxonomy kinds "
          "(`location`, `organization`) are neutralised, not scored.",
          "- Model scores are not calibrated probabilities. No claim of calibration is made.",
          "- A language is only 'supported' where its slice above shows adequate scores; zero-shot slices are reported, not endorsed.", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", help="fine-tuned checkpoint dir (omit to evaluate rules only)")
    ap.add_argument("--name", required=True)
    ap.add_argument("--sets", default=",".join(TEST_SETS))
    ap.add_argument("--systems", default="rules,transformer,hybrid")
    ap.add_argument("--limit", type=int, default=0, help="score only N documents per set (seeded shuffle)")
    args = ap.parse_args()

    import psutil

    proc = psutil.Process()
    rss_before = proc.memory_info().rss
    systems, ner = build_systems(args.model, args.systems.split(","))
    rss_after = proc.memory_info().rss
    meta_path = Path(args.model) / "pii_ner_meta.json" if args.model else None
    res = {
        "name": args.name, "generated_at": time.strftime("%Y-%m-%d %H:%M"), "platform": platform.platform(),
        "systems": list(systems), "limit": args.limit,
        "model_meta": json.loads(meta_path.read_text(encoding="utf-8")) if meta_path and meta_path.is_file() else None,
        "model_memory_mb": round((rss_after - rss_before) / 1e6) if ner else None, "results": {},
    }
    for ts in args.sets.split(","):
        docs = read_jsonl(ROOT / "data" / "processed" / ("validation.jsonl" if ts == "validation" else f"test_{ts}.jsonl"))
        if args.limit:
            random.Random(7).shuffle(docs)
            docs = docs[: args.limit]
        res["results"][ts] = {}
        for name, fn in systems.items():
            t0 = time.time()
            preds, perf = run_system(fn, docs)
            res["results"][ts][name] = {"perf": perf, "metrics": evaluate(docs, preds)}
            m = res["results"][ts][name]["metrics"]["strict"]["micro"]
            print(f"{ts:28} {name:12} P={m['precision']:.3f} R={m['recall']:.3f} F1={m['f1']:.3f}  ({time.time() - t0:.0f}s)", flush=True)
    out = ROOT / "evaluation" / args.name
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(res, indent=2, ensure_ascii=False), encoding="utf-8")
    (out / "report.md").write_text(render_report(res), encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
